"""Настройки приложения.

REPO прописывается автоматически при сборке на GitHub (файл
app/build_config.py создаёт workflow). Тогда приложение берёт свежий
проверенный список из ветки «proxies» вашего репозитория.
"""

try:
    from .build_config import REPO
except Exception:
    REPO = ""

DATA_BRANCH = "proxies"     # ветка, куда робот кладёт проверенный список
DATA_FILE = "proxies.json"

CHECK_TIMEOUT = 7.0         # секунд на одну проверку
WORKERS = 24                # одновременных проверок на телефоне
MAX_CHECK = 400             # сколько новых кандидатов проверять за один проход
ENOUGH_WORKING = 40         # нашли столько рабочих — дальше не ищем (бережём батарею)
MIN_WORKING = 5             # если рабочих меньше — сразу ищем новые
MIN_CURATED = 30            # если в своём списке меньше — берём ещё открытые списки
RECHECK_EVERY = 240         # секунд между перепроверками рабочих
FULL_EVERY = 3600           # раз в час заново скачиваем списки (если приложение открыто)
REFETCH_AFTER = 600         # не качать списки чаще, чем раз в 10 минут (кроме «Обновить»)
RETRY_FAILED_AFTER = 1800   # нерабочий прокси пробуем снова не раньше чем через 30 минут
OFFLINE_RETRY = 20          # нет интернета — пробуем снова через 20 с (потом реже)
KEEP_MAX = 800              # сколько прокси хранить в кэше на телефоне
SHOW_MAX = 50               # сколько рабочих показывать в списке


def curated_urls():
    if not REPO:
        return []
    return ["https://raw.githubusercontent.com/%s/%s/%s" % (REPO, DATA_BRANCH, DATA_FILE)]
